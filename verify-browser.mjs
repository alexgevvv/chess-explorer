const baseUrl = (process.env.TEST_BASE_URL || 'http://localhost:5174').replace(/\/$/, '')
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const response = await page.goto(baseUrl + '/', { waitUntil: 'domcontentloaded' });
  assert.equal(response.status(), 200);
  await expect(page.getByRole('heading', { name: 'Chess Explorer' })).toBeVisible();
  const square = (name) => page.locator('[data-square="' + name + '"]');
  const move = async (from, to) => { await square(from).click(); await square(to).click(); };
  const board = page.getByTestId('board');
  const startFen = await board.getAttribute('data-fen');
  await move('e2', 'e5');
  assert.equal(await board.getAttribute('data-fen'), startFen);
  await move('e2', 'e4');
  await expect(square('e4').locator('[data-piece="wP"]')).toBeVisible();
  await expect(page.locator('.turn-status')).toHaveText('Black to move');
  await expect(page.getByRole('region', { name: 'Move statistics' })).toContainText('Enter a Chess.com nickname');
  await move('e7', 'e5');
  await expect(page.locator('.turn-status')).toHaveText('White to move');
  await page.getByRole('button', { name: 'Previous move', exact: true }).click();
  await move('c7', 'c5');
  await expect(page.getByRole('button', { name: '1... e5', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '1... c5', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Make main line' }).click();
  await page.getByRole('button', { name: 'Flip board' }).click();
  assert.equal(await page.locator('[data-square]').first().getAttribute('data-square'), 'h1');
  await page.getByRole('button', { name: 'Previous move', exact: true }).click();
  await expect(page.locator('.color-tag')).toHaveText('Black games');
  await page.getByRole('button', { name: 'Next move', exact: true }).click();
  await expect(square('c5').locator('[data-piece="bP"]')).toBeVisible();
  const loadFen = async (fen) => {
    await page.getByRole('button', { name: 'FEN / PGN', exact: true }).click();
    await page.getByRole('button', { name: 'FEN', exact: true }).click();
    await page.getByLabel('Position in FEN format').fill(fen);
    await page.getByRole('button', { name: 'Load FEN', exact: true }).click();
  };
  await loadFen('8/P6k/8/8/8/8/8/7K w - - 0 34');
  await move('a7', 'a8');
  await expect(page.getByRole('dialog', { name: 'Promote pawn' })).toBeVisible();
  await page.getByRole('button', { name: 'Promote to knight', exact: true }).click();
  await expect(square('a8').locator('[data-piece="wN"]')).toBeVisible();
  await expect(page.getByRole('button', { name: '34. a8=N', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'FEN / PGN', exact: true }).click();
  await page.getByRole('button', { name: 'PGN', exact: true }).click();
  await page.getByLabel('Game in PGN format').fill('1. e4 e5 2. Nf3 Nc6 3. Bb5 a6');
  await page.getByRole('button', { name: 'Load PGN', exact: true }).click();
  await page.getByRole('button', { name: 'Last position', exact: true }).click();
  await expect(square('b5').locator('[data-piece="wB"]')).toBeVisible();
  const beforeInvalid = await board.getAttribute('data-fen');
  await loadFen('invalid position');
  await expect(page.getByRole('alert')).toBeVisible();
  assert.equal(await board.getAttribute('data-fen'), beforeInvalid);
  await page.keyboard.press('Escape');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(board).toHaveAttribute('data-fen', startFen);
  assert.equal(await page.locator('[data-square]').first().getAttribute('data-square'), 'a8');
  const src = await square('d2').boundingBox(), dst = await square('d4').boundingBox();
  await page.mouse.move(src.x + src.width / 2, src.y + src.height / 2);
  await page.mouse.down();
  await page.mouse.move(dst.x + dst.width / 2, dst.y + dst.height / 2, { steps: 12 });
  await page.mouse.up();
  await expect(square('d4').locator('[data-piece="wP"]')).toBeVisible();
  await page.getByRole('button', { name: 'Clear analysis', exact: true }).click();
  await expect(board).toHaveAttribute('data-fen', startFen);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'preview-mobile.png', fullPage: true });
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: 'preview-dark.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS: HTTP 200, 64 squares, tap, drag, illegal move rejection, notation, empty explorer without a selected player, flip, branches, main-line selection, navigation, promotion, PGN, invalid FEN, reset, no persistence, light/dark themes, mobile/desktop layout, no runtime errors.');
} finally { await browser.close(); }
