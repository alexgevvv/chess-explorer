import assert from 'node:assert/strict'
import { Chess } from 'chess.js'
import { prepareGame, calculateStats, defaultFilters, positionKey } from './src/data.ts'
import { importPgn, gameAt, treeFromMoves } from './src/board.ts'
import { validatePosition } from './src/position.ts'
import { fixtureGames, nickname, raw } from './test-fixtures.mjs'
const records = fixtureGames.map((game) => prepareGame(game, nickname)).filter(Boolean)
assert.equal(records.length, 13)
const start = new Chess().fen(), filters = defaultFilters()
let stats = calculateStats(records, start, 'w', filters)
assert.equal(stats.total, 11)
assert.equal(stats.moves.length, 6)
assert.equal(stats.moves.find((move) => move.san === 'Nf3').count, 4)
assert.deepEqual(stats.moves.find((move) => move.san === 'e4'), { san: 'e4', count: 2, wins: 1, draws: 0, losses: 1 })
const game = new Chess(); for (const san of ['d4','Nf6','Nf3','d5']) game.move(san)
stats = calculateStats(records, game.fen(), 'w', filters)
assert.equal(stats.total, 4)
assert.equal(stats.ended, 1)
assert.deepEqual(stats.moves.find((move) => move.san === 'e3'), { san: 'e3', count: 2, wins: 1, draws: 0, losses: 1 })
assert.equal(stats.moves.find((move) => move.san === 'c4').draws, 1)
const blackGame = new Chess(); blackGame.move('e4')
stats = calculateStats(records, blackGame.fen(), 'b', filters)
assert.equal(stats.total, 2)
assert.equal(stats.moves.find((move) => move.san === 'e5').wins, 1)
assert.equal(stats.moves.find((move) => move.san === 'c5').losses, 1)
stats = calculateStats(records, start, 'w', { ...filters, from: '2026-01-03', to: '2026-01-05', minRating: '1800', maxRating: '1900' })
assert.equal(stats.total, 2)
assert.equal(calculateStats(records, start, 'w', { ...filters, classes: [] }).total, 0)
assert.equal(positionKey(start), positionKey(start.replace('0 1', '19 25')))
assert.notEqual(positionKey(start), positionKey(start.replace('KQkq', '-')))
assert.throws(() => validatePosition('7k/8/8/8/8/8/8/K6R w - - 0 1'))
const branch = importPgn('1. e4 e5 (1... c5 2. Nf3 d6 (2... Nc6)) 2. Nf3 Nc6')
assert.equal(branch.nodes['1'].children.length, 2)
assert.ok(Object.values(branch.nodes).some((node) => node.san === 'd6'))
const record = prepareGame(raw('load', 'e4 e5 Nf3 Nc6'), nickname)
assert.equal(gameAt(treeFromMoves(record.startFen, record.moves, 2)).fen(), (() => { const c = new Chess(); c.move('e4'); c.move('e5'); return c.fen() })())
